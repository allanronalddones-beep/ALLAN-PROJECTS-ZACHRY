"""Regenerate assets/search-index.js from the chapter HTML.

Run from the tool root:   python tools/build_search_index.py

Reads every ch*.html, extracts each addressable section, and writes a plain
.js file (not .json) because the search must work from file:// where fetch()
is blocked.
"""
import io, re, json, os, sys

# always resolve against the tool root, whatever directory we were called from
os.chdir(os.path.join(os.path.dirname(os.path.abspath(__file__)), os.pardir))


CH = {
 'ch01-units-formulas.html': 'Ch.1 Units, Conversions & Formulas',
 'ch02-standards.html':      'Ch.2 Standards',
 'ch03-materials.html':      'Ch.3 Materials',
 'ch04-pumps.html':          'Ch.4 Pump Selection',
 'ch05-compressors.html':    'Ch.5 Compressor Selection',
 'ch06-expanders.html':      'Ch.6 Expander Selection',
 'ch07-steam-turbines.html': 'Ch.7 Steam Turbine Selection',
 'ch08-gas-turbines.html':   'Ch.8 Gas Turbine Selection',
 'ch09-coupling.html':       'Ch.9 Coupling',
 'ch10-heat-exchangers.html':'Ch.10 Heat Exchanger',
 'ch11-electrical.html':     'Ch.11 Electrical',
 'ch12-trade-terms.html':    'Ch.12 Trade Terms',
 'ch13-construction.html':   'Ch.13 Construction',
 'ch14-operation.html':      'Ch.14 Operation',
}

STOP = set("""a an and are as at be been but by can could do does for from had has have how if in
into is it its may might must not of on or over should such than that the their then there these
this those through to under up use used using was were what when where which while who will with
within would you your it's also both each either neither per very more most less least only same
other another any all some few many much them they we our one two three first second new now here
after before between during above below out off down about against because so very just like
via upon onto towards toward across along among around behind beneath beside besides beyond
despite except inside outside since until unless whether while whose whom why whereas thereby
however therefore moreover furthermore nevertheless nonetheless""".split())

H = re.compile(r'<h([234])(?:\s+id="(s[\d-]+)")?>\s*(?:<span class="sec-no">([\d.]+)</span>)?(.*?)</h\1>', re.S)
CAP = re.compile(r'<caption>(.*?)</caption>', re.S)
SCRIPT = re.compile(r'<(script|style|svg|math)\b.*?</\1>', re.S|re.I)

def text_of(html):
    html = SCRIPT.sub(' ', html)
    s = re.sub(r'<[^>]+>', ' ', html)
    for a,b in (('&amp;','&'),('&nbsp;',' '),('&lt;','<'),('&gt;','>'),('&mdash;',' '),
                ('&ndash;',' '),('&reg;',' '),('&times;',' '),('&le;',' '),('&ge;',' ')):
        s = s.replace(a,b)
    return ' '.join(s.split())

def clean_inline(s):
    s = re.sub(r'<[^>]+>', '', s)
    for a,b in (('&amp;','&'),('&nbsp;',' '),('&lt;','<'),('&gt;','>')):
        s = s.replace(a,b)
    return ' '.join(s.split())

def tokens(s, limit):
    s = s.lower()
    # hyphen separates, matching the client tokenizer in reference.js
    s = re.sub(r'[^a-z0-9₀-₉+/·°%\s]', ' ', s)
    seen, out, n = set(), [], 0
    for w in s.split():
        w = w.strip('/·')
        if len(w) < 2 or w in STOP or w in seen: continue
        seen.add(w); out.append(w); n += len(w) + 1
        if n > limit: break
    return ' '.join(out)

entries = []
for fn in sorted(CH):
    if not os.path.exists(fn): print('MISSING', fn); continue
    txt = io.open(fn, encoding='utf-8').read()
    chapter = CH[fn]
    hs = [(m.start(), int(m.group(1)), m.group(2), m.group(3), clean_inline(m.group(4)))
          for m in H.finditer(txt)]
    anchors = [h for h in hs if h[2] and h[1] in (2,3)]
    for k,h in enumerate(anchors):
        start = h[0]
        end = anchors[k+1][0] if k+1 < len(anchors) else len(txt)
        title, num = h[4], (h[3] or '')
        if title.lower().startswith('sources'):
            title = f'Sources (Chapter {num.split(".")[0]})'
        seg = txt[start:end]
        # 'head' carries this section's own sub-headings and table captions.
        # Weighted above body text so a term that titles a subsection ranks
        # that subsection ahead of a section that merely mentions it.
        head = ' '.join([title]
                        + [clean_inline(x[4]) for x in hs if start < x[0] < end]
                        + [clean_inline(c) for c in CAP.findall(seg)])
        head = re.sub(r'table [\d.\-]+', ' ', head, flags=re.I)
        entries.append({
            'ref': num, 'title': title, 'url': f'{fn}#{h[2]}', 'chapter': chapter,
            'head': tokens(head, 400),
            'terms': tokens(text_of(seg), 1100),
        })

out = io.open('assets/search-index.js','w',encoding='utf-8')
out.write("""/* Search index for the Rotating Equipment General Reference.
   Loaded as a plain script, not fetched, so that search works from file://.

   GENERATED by tools-build-search-index.py. Do not hand-edit.
   "head"  = this section's own sub-headings and table captions (high weight)
   "terms" = the distinct, stopword-filtered words of its body text (low weight)
   so search reaches body content while headings still win the ranking. */

window.REF_INDEX = [
""")
for i,e in enumerate(entries):
    out.write('  ' + json.dumps(e, ensure_ascii=False) + (',' if i < len(entries)-1 else '') + '\n')
out.write('];\n')
out.close()
print('entries:', len(entries), '| index size:', os.path.getsize('assets/search-index.js')//1024, 'KB')
